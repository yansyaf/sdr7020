// expio_io.v - maps an AXI GPIO onto the expansion-header pins as named signals,
//              and generates the synchronisation pulse for the motion controller.
//
// The block design sees one 12-bit output word and one 12-bit input word; this
// wrapper gives those bits the names used in expio.xdc, so the constraints stay
// readable and a clocked step generator can later replace the direct assigns
// without touching the pinout.
//
// Output word                                  Input word
//   out[0]  step_x        3V3_IO1               in[0] limit_x
//   out[1]  step_y        3V3_IO2               in[1] limit_y
//   out[2]  step_r        3V3_IO3               in[2] limit_r
//   out[3]  ena_n         3V3_IO4               in[3] sync_from_grbl level
//   out[4]  dir_x         1V8_IO1_N             in[4] sync pulse busy
//   out[5]  dir_y         1V8_IO3_N             in[5] sync pulse toggle (activity)
//   out[6]  dir_r         1V8_IO5_N             in[11:6] zero
//   out[7]  ptt_io        PTT_IO
//   out[8..9] unused
//   out[10] sync_sw       rising edge fires a sync pulse
//   out[11] sync_src      1 = also echo edges arriving on sync_from_grbl
//
// sync_to_grbl comes from sync_pulse: a firmware-triggerable pulse whose edge is
// what the motion controller sees as "the measurement window opened". With
// out[11] set the pulse is generated by the hardware echo instead, so the
// handshake needs no software in the loop at all.
`timescale 1ns / 1ps

module expio_io #(
    parameter integer PULSE_CLKS = 1000
) (
    input  wire        clk,

    input  wire [11:0] gpio_out,
    output wire [11:0] gpio_in,

    // bank 13, 3.3 V
    output wire        step_x,
    output wire        step_y,
    output wire        step_r,
    output wire        step_ena_n,

    // bank 35, 1.8 V
    output wire        dir_x,
    output wire        dir_y,
    output wire        dir_r,
    output wire        ptt_io,

    // handshake with the motion controller, 1V8_IO7_P / 1V8_IO7_N
    output wire        sync_to_grbl,
    input  wire        sync_from_grbl,

    // bank 35, 1.8 V, divided from the switches
    input  wire        limit_x,
    input  wire        limit_y,
    input  wire        limit_r
);

    // ---- motion signals ---------------------------------------------------
    assign step_x     = gpio_out[0];
    assign step_y     = gpio_out[1];
    assign step_r     = gpio_out[2];
    assign step_ena_n = gpio_out[3];

    assign dir_x      = gpio_out[4];
    assign dir_y      = gpio_out[5];
    assign dir_r      = gpio_out[6];
    assign ptt_io     = gpio_out[7];

    // ---- sync pulse -------------------------------------------------------
    wire pulse_busy;
    wire ext_level;
    wire pulse_toggle;

    sync_pulse #(.PULSE_CLKS(PULSE_CLKS)) u_sync (
        .clk            (clk),
        .rst            (1'b0),
        .sw_trig        (gpio_out[10]),
        .src_sel        (gpio_out[11]),
        .ext_in         (sync_from_grbl),
        .pulse_out      (sync_to_grbl),
        .ext_level      (ext_level),
        .busy           (pulse_busy),
        .pulse_count_lo (pulse_toggle)
    );

    // ---- status back to software -----------------------------------------
    assign gpio_in = {6'b0, pulse_toggle, pulse_busy, ext_level,
                      limit_r, limit_y, limit_x};

endmodule
